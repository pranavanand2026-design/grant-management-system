/* Core formatting shared by the design system and application. */

export const ISO = /^\d{4}-\d{2}-\d{2}$/;

export function esc(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

export function money(v, opts) {
  if (v == null || isNaN(v)) return null;
  const n = Math.round(v);
  if (opts && opts.abbrev && Math.abs(n) >= 100000) {
    return "$" + (n / 1000).toLocaleString("en-AU", { maximumFractionDigits: 0 }) + "k";
  }
  return "$" + n.toLocaleString("en-AU");
}

export function fmtDate(iso) {
  if (!ISO.test(iso || "")) return iso || null;
  return new Date(iso + "T00:00:00").toLocaleDateString("en-AU",
    { day: "numeric", month: "short", year: "numeric" });
}

